/**
 * Reads the GDR YAML files under content/ and writes them as one TypeScript module, so that the Game build carries
 * its GDRs without a YAML parser. It reads only this Implementation directory.
 *
 * - A top-level mapping becomes an object.
 * - A nested mapping becomes `{ $entries: [[key, value], ...] }`, which preserves the authored key order even for
 *   keys that look like whole numbers; see GDR, GDR authoring format.
 * - A number with a fractional part becomes `{ $decimal: "<text as written>" }`, so that it is never read as a
 *   binary floating-point number; see NUMBERS, Whole-number quantities.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { isMap, isScalar, isSeq, parseAllDocuments } from 'yaml';

const root = join(import.meta.dirname, '..');
const contentDir = join(root, 'content');
const outFile = join(root, 'src', 'gdr', 'generated', 'raw-gdrs.ts');

function listYamlFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...listYamlFiles(full));
    } else if (entry.name.endsWith('.yaml')) {
      out.push(full);
    }
  }
  return out.sort();
}

function convert(node: unknown, topLevel: boolean, where: string): unknown {
  if (isMap(node)) {
    const entries: [string, unknown][] = node.items.map((pair) => {
      const key = isScalar(pair.key) ? String(pair.key.value) : String(pair.key);
      return [key, convert(pair.value, false, `${where}.${key}`)];
    });
    return topLevel ? Object.fromEntries(entries) : { $entries: entries };
  }
  if (isSeq(node)) {
    return node.items.map((item, index) => convert(item, false, `${where}[${index}]`));
  }
  if (isScalar(node)) {
    const value = node.value;
    if (typeof value === 'number') {
      const source = (node.source ?? String(value)).trim();
      if (/^[+-]?\d+$/.test(source)) {
        if (!Number.isSafeInteger(value)) {
          throw new Error(`${where}: whole number out of range: ${source}`);
        }
        return value;
      }
      if (!/^[+-]?\d+\.\d+$/.test(source)) {
        throw new Error(`${where}: unsupported number format: ${source}`);
      }
      return { $decimal: source };
    }
    if (typeof value === 'string' || typeof value === 'boolean' || value === null) {
      return value;
    }
    throw new Error(`${where}: unsupported scalar`);
  }
  if (node === null || node === undefined) {
    return null;
  }
  throw new Error(`${where}: unsupported YAML node`);
}

const files = listYamlFiles(contentDir).map((file) => {
  const path = relative(contentDir, file).replaceAll('\\', '/');
  const documents = parseAllDocuments(readFileSync(file, 'utf8'));
  const gdrs = documents.map((document, index) => {
    if (document.errors.length > 0) {
      throw new Error(`${path}: ${document.errors[0]!.message}`);
    }
    return convert(document.contents, true, `${path}#${index}`);
  });
  return { path, gdrs };
});

const json = JSON.stringify(files, null, 2);

const moduleText = `// Generated by scripts/build-gdr.ts from content/. Do not edit.
export const RAW_GDR_FILES: readonly { readonly path: string; readonly gdrs: readonly unknown[] }[] = ${json};
`;

mkdirSync(join(root, 'src', 'gdr', 'generated'), { recursive: true });
let previous = '';
try {
  previous = readFileSync(outFile, 'utf8');
} catch {
  // first build
}
if (previous !== moduleText) {
  writeFileSync(outFile, moduleText);
}
console.log(`gdr build: ${files.length} files, ${files.reduce((n, f) => n + f.gdrs.length, 0)} GDRs`);
